//! Journée's (1992) tables for Wigley I and III, as printed, transcribed from Report 0909 on
//! 2026-11-20 (page by page with `pdftotext -layout`, checked against the page images where a
//! column was blank, then re-extracted and compared number by number). A blank in the table is
//! `None`; added resistance (Table 8) is not transcribed.
//!
//! Normalisation (§4.1 to §4.3), with ∇ the printed volume, ρ = 1000 kg/m³ and g = 9.81 m/s²:
//! ω″ = ω√(L/g), where ω is the oscillation frequency, so the encounter frequency;
//! A33″ = A33/(ρ∇), B33″ = B33/(ρ∇√(g/L)); A35″, A53″ = A/(ρ∇L), B35″, B53″ = B/(ρ∇L√(g/L));
//! A55″ = A55/(ρ∇L²), B55″ = B55/(ρ∇L²√(g/L)); Xw3″ = Xw3a/(ζa·C33), Xw5″ = Xw5a/(k·ζa·C55);
//! z″ = za/ζa, θ″ = θa·L/(2π·ζa). Phases in degrees relative to the wave at the centre of gravity,
//! pitch positive bow down (Journée's axes, Appendix I).

/// One forced-oscillation measurement: one speed, one oscillation amplitude, one frequency.
#[derive(Debug, Clone, Copy)]
pub struct ForcedRow {
    pub froude: f64,
    /// Oscillation amplitude: metres for heave (Table 2), degrees for pitch (Table 3).
    pub amplitude: f64,
    /// ω″ = ω√(L/g).
    pub omega_nd: f64,
    /// A33″ (Table 2) or A55″ (Table 3).
    pub a_direct: Option<f64>,
    /// B33″ (Table 2) or B55″ (Table 3).
    pub b_direct: Option<f64>,
    /// A53″ (Table 2) or A35″ (Table 3).
    pub a_coupled: Option<f64>,
    /// B53″ (Table 2) or B35″ (Table 3).
    pub b_coupled: Option<f64>,
}

/// One restrained-model wave-load measurement: one speed, one λ/L, one wave amplitude.
#[derive(Debug, Clone, Copy)]
pub struct WaveLoadRow {
    pub froude: f64,
    pub lambda_over_l: f64,
    /// Wave amplitude (cm).
    pub zeta_a_cm: f64,
    pub xw3: Option<f64>,
    pub eps3_deg: Option<f64>,
    pub xw5: Option<f64>,
    pub eps5_deg: Option<f64>,
}

/// One free-model motion measurement: one speed, one λ/L, one wave amplitude.
#[derive(Debug, Clone, Copy)]
pub struct MotionRow {
    pub froude: f64,
    pub lambda_over_l: f64,
    /// Wave amplitude (cm).
    pub zeta_a_cm: f64,
    pub z: Option<f64>,
    pub eps_z_deg: Option<f64>,
    pub theta: Option<f64>,
    pub eps_theta_deg: Option<f64>,
}

const fn f(
    froude: f64,
    amplitude: f64,
    omega_nd: f64,
    a: f64,
    b: f64,
    ac: f64,
    bc: f64,
) -> ForcedRow {
    ForcedRow {
        froude,
        amplitude,
        omega_nd,
        a_direct: Some(a),
        b_direct: Some(b),
        a_coupled: Some(ac),
        b_coupled: Some(bc),
    }
}

#[allow(clippy::too_many_arguments)]
const fn w(
    froude: f64,
    lambda_over_l: f64,
    zeta_a_cm: f64,
    xw3: Option<f64>,
    eps3_deg: Option<f64>,
    xw5: Option<f64>,
    eps5_deg: Option<f64>,
) -> WaveLoadRow {
    WaveLoadRow {
        froude,
        lambda_over_l,
        zeta_a_cm,
        xw3,
        eps3_deg,
        xw5,
        eps5_deg,
    }
}

#[allow(clippy::too_many_arguments)]
const fn m(
    froude: f64,
    lambda_over_l: f64,
    zeta_a_cm: f64,
    z: Option<f64>,
    eps_z_deg: Option<f64>,
    theta: Option<f64>,
    eps_theta_deg: Option<f64>,
) -> MotionRow {
    MotionRow {
        froude,
        lambda_over_l,
        zeta_a_cm,
        z,
        eps_z_deg,
        theta,
        eps_theta_deg,
    }
}

