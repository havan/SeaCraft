//! Repository checks that need no build: private files, skill routing, the
//! third-party licence list and colour literals. Pure functions over text and
//! file lists; `main.rs` holds the thin git and filesystem wrappers.

/// Folders kept on a contributor's machine, never in the repository.
pub const PRIVATE_PREFIXES: &[&str] =
    &[".hermes/", ".claude/", "plan/", ".local/", ".superpowers/"];

/// Tracked files that may name private folders: the rule itself.
pub const PRIVATE_TEXT_ALLOWED: &[&str] = &[".gitignore", "xtask/src/gates.rs"];

/// Tracked paths under a private folder.
pub fn private_path_violations(files: &[String]) -> Vec<String> {
    files
        .iter()
        .filter(|f| PRIVATE_PREFIXES.iter().any(|p| f.starts_with(p)))
        .cloned()
        .collect()
}

/// Lines of `text` naming a private folder, a sibling checkout or one of
/// `machine_paths` (this checkout's absolute path and the home directory, read
/// at run time so that no private path has to be written in this file).
pub fn private_text_violations(path: &str, text: &str, machine_paths: &[String]) -> Vec<String> {
    if PRIVATE_TEXT_ALLOWED.contains(&path) {
        return Vec::new();
    }
    let fixed = [".hermes/", "../resource"];
    let mut out = Vec::new();
    for (i, line) in text.lines().enumerate() {
        let machine = machine_paths.iter().map(String::as_str);
        if let Some(hit) = fixed.into_iter().chain(machine).find(|n| line.contains(n)) {
            out.push(format!("{path}:{}: names {hit}", i + 1));
        }
    }
    out
}

/// What `AGENTS.md` and `skills/README.md` claim against what exists.
/// `skill_dirs` holds the folder names under `skills/`; `exists` answers for a
/// repository-relative path; `commands` lists the `cargo xtask` subcommands.
pub fn skills_violations(
    agents: &str,
    skills_readme: &str,
    skill_dirs: &[String],
    exists: &dyn Fn(&str) -> bool,
    commands: &[&str],
) -> Vec<String> {
    let mut out = Vec::new();
    for dir in skill_dirs {
        if !skills_readme.contains(&format!("]({dir}/SKILL.md)")) {
            out.push(format!("skills/README.md does not list skill {dir}"));
        }
    }
    for chunk in skills_readme.split("](").skip(1) {
        if let Some((target, _)) = chunk.split_once(')') {
            if target.ends_with("/SKILL.md") && !exists(&format!("skills/{target}")) {
                out.push(format!("skills/README.md links to missing skills/{target}"));
            }
        }
    }
    for (name, text) in [("AGENTS.md", agents), ("skills/README.md", skills_readme)] {
        for token in text.split('`').skip(1).step_by(2) {
            if let Some(rest) = token.strip_prefix("cargo xtask ") {
                let command = rest.split_whitespace().next().unwrap_or("");
                if !commands.contains(&command) {
                    out.push(format!("{name} names unknown command `{token}`"));
                }
            } else if name == "AGENTS.md" && is_repo_path(token) && !exists(token) {
                out.push(format!("AGENTS.md names missing file `{token}`"));
            }
        }
    }
    out
}

/// A backticked token that reads as a file in the repository.
fn is_repo_path(token: &str) -> bool {
    !token.contains([' ', '*', '<'])
        && [".md", ".toml", ".rs", ".yml"]
            .iter()
            .any(|ext| token.ends_with(ext))
}

/// One dependency in `THIRD-PARTY-LICENSES.txt`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Dep {
    pub name: String,
    pub version: String,
    pub license: String,
    pub repository: String,
}

/// The file's whole content for `deps`, in a stable order.
pub fn licences_render(deps: &[Dep]) -> String {
    let mut sorted = deps.to_vec();
    sorted.sort();
    let mut out = String::from(
        "Third-party licences of SeaCraft's dependencies.\n\
         Generated by `cargo xtask licences` from Cargo.lock; do not edit.\n\n",
    );
    for d in &sorted {
        out.push_str(&format!(
            "{} {}\n  licence: {}\n  source: {}\n",
            d.name, d.version, d.license, d.repository
        ));
    }
    out
}

/// One crate compiled into a package, and the licence files it publishes.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct ShippedCrate {
    pub dep: Dep,
    pub authors: Vec<String>,
    /// File name and contents.
    pub files: Vec<(String, String)>,
}

/// Whether a file at the top of a crate, by its name, is a licence or notice.
pub fn is_licence_file(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    let code = [".rs", ".toml", ".json", ".html", ".yml", ".yaml"];
    ["licen", "copying", "notice", "copyright", "unlicense"]
        .iter()
        .any(|p| lower.starts_with(p))
        && !code.iter().any(|e| lower.ends_with(e))
}

/// The licence names in a Cargo `license` expression, such as `MIT/Apache-2.0`.
pub fn licence_ids(expression: &str) -> Vec<String> {
    expression
        .split(|c: char| c.is_whitespace() || "()/".contains(c))
        .filter(|t| !t.is_empty() && !["OR", "AND", "WITH"].contains(t))
        .filter(|t| !t.ends_with("-exception"))
        .map(str::to_owned)
        .collect()
}

/// The full `THIRD-PARTY-LICENSES.txt` of a package: every crate, then each distinct licence file
/// once with the crates that carry it, then the standard text for any crate that publishes no
/// licence file. Fails when such a crate names a licence with no text in `standard`.
pub fn licence_texts_render(
    heading: &str,
    crates: &[ShippedCrate],
    standard: &[(&str, String)],
) -> Result<String, String> {
    let mut sorted = crates.to_vec();
    sorted.sort();
    let label = |c: &ShippedCrate| format!("{} {}", c.dep.name, c.dep.version);
    let rule = "=".repeat(78);

    let mut out = format!("{heading}\nGenerated by `cargo xtask dist`; do not edit.\n\n");
    out.push_str(&format!("{rule}\nCRATES\n{rule}\n\n"));
    let mut needed = std::collections::BTreeSet::new();
    for c in &sorted {
        out.push_str(&format!(
            "{}\n  licence: {}\n  source: {}\n",
            label(c),
            c.dep.license,
            c.dep.repository
        ));
        if c.files.is_empty() {
            out.push_str(&format!(
                "  authors: {}\n  no licence file in the published crate; see STANDARD TEXTS\n",
                c.authors.join(", ")
            ));
            for id in licence_ids(&c.dep.license) {
                if !standard.iter().any(|(name, _)| *name == id) {
                    return Err(format!(
                        "{} publishes no licence file and there is no standard text for {id}",
                        label(c)
                    ));
                }
                needed.insert(id);
            }
        }
    }

    // Most crates carry the same few texts: one copy of each, in a stable order.
    let mut groups: std::collections::BTreeMap<String, Vec<String>> = Default::default();
    for c in &sorted {
        for (file, text) in &c.files {
            let text = text.replace("\r\n", "\n").trim().to_owned();
            groups
                .entry(text)
                .or_default()
                .push(format!("{} ({file})", label(c)));
        }
    }
    let mut groups: Vec<_> = groups.into_iter().collect();
    groups.sort_by(|a, b| a.1.cmp(&b.1));
    out.push_str(&format!("\n{rule}\nLICENCE FILES\n{rule}\n"));
    for (text, users) in &groups {
        out.push_str(&format!(
            "\n{}\nUsed by: {}\n\n{text}\n",
            "-".repeat(78),
            users.join(", ")
        ));
    }

    if !needed.is_empty() {
        out.push_str(&format!("\n{rule}\nSTANDARD TEXTS\n{rule}\n"));
        for (name, text) in standard {
            if needed.contains(*name) {
                out.push_str(&format!("\n{}\n{name}\n\n{text}\n", "-".repeat(78)));
            }
        }
    }
    Ok(out)
}

/// Calls that build a colour from numbers, outside the theme file.
pub fn colour_violations(path: &str, text: &str) -> Vec<String> {
    if path.ends_with("/theme.rs") {
        return Vec::new();
    }
    let mut out = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if line.contains("Color32::from_") {
            out.push(format!("{path}:{}: colour literal, use theme.rs", i + 1));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(v: &[&str]) -> Vec<String> {
        v.iter().map(|x| x.to_string()).collect()
    }

    #[test]
    fn private_flags_tracked_hermes_file() {
        let bad = private_path_violations(&s(&[".hermes/NEXT.md", "README.md", "plan/a.md"]));
        assert_eq!(bad, s(&[".hermes/NEXT.md", "plan/a.md"]));
    }

    #[test]
    fn private_ignores_names_that_only_look_private() {
        assert!(private_path_violations(&s(&["docs/plan/a.md", "planets.md"])).is_empty());
    }

    #[test]
    fn private_flags_local_path_in_text() {
        let machine = s(&["/srv/me/repo", "/home/me"]);
        let bad = private_text_violations(
            "docs/a.md",
            "fine\nsee /srv/me/repo/x\nsee /home/me/y\nsee ../resource/z\nsee .hermes/NEXT.md\n",
            &machine,
        );
        assert_eq!(bad.len(), 4, "{bad:?}");
        assert!(bad[0].starts_with("docs/a.md:2:"), "{bad:?}");
    }

    #[test]
    fn private_allows_gate_and_ignore_rules() {
        let bad = private_text_violations(".gitignore", "/.hermes/\n", &[]);
        assert!(bad.is_empty(), "{bad:?}");
        let bad = private_text_violations("xtask/src/gates.rs", "../resource\n", &[]);
        assert!(bad.is_empty(), "{bad:?}");
    }

    fn check(agents: &str, readme: &str, dirs: &[&str]) -> Vec<String> {
        let dirs = s(dirs);
        let known = dirs.clone();
        let exists = move |p: &str| {
            p == "ROADMAP.md" || known.iter().any(|d| p == format!("skills/{d}/SKILL.md"))
        };
        skills_violations(agents, readme, &dirs, &exists, &["ci", "private"])
    }

    #[test]
    fn skills_passes_when_everything_agrees() {
        let bad = check(
            "`skills/a/SKILL.md` `ROADMAP.md` `cargo xtask private`",
            "[a](a/SKILL.md) [b](b/SKILL.md)",
            &["a", "b"],
        );
        assert!(bad.is_empty(), "{bad:?}");
    }

    #[test]
    fn skills_flags_missing_file() {
        let bad = check(
            "`skills/gone/SKILL.md` `MISSING.md`",
            "[a](a/SKILL.md)",
            &["a"],
        );
        assert_eq!(bad.len(), 2, "{bad:?}");
    }

    #[test]
    fn skills_flags_unlisted_skill() {
        let bad = check("", "[a](a/SKILL.md)", &["a", "b"]);
        assert_eq!(bad.len(), 1, "{bad:?}");
        assert!(bad[0].contains('b'), "{bad:?}");
    }

    #[test]
    fn skills_flags_unknown_xtask_command() {
        let bad = check("`cargo xtask nope`", "[a](a/SKILL.md)", &["a"]);
        assert_eq!(bad.len(), 1, "{bad:?}");
    }

    fn dep(name: &str, version: &str) -> Dep {
        Dep {
            name: name.into(),
            version: version.into(),
            license: "MIT".into(),
            repository: "https://example.org".into(),
        }
    }

    fn shipped(name: &str, license: &str, files: &[(&str, &str)]) -> ShippedCrate {
        ShippedCrate {
            dep: Dep {
                license: license.to_owned(),
                ..dep(name, "1.0.0")
            },
            authors: vec!["An Author".to_owned()],
            files: files
                .iter()
                .map(|(f, t)| ((*f).to_owned(), (*t).to_owned()))
                .collect(),
        }
    }

    #[test]
    fn licence_files_are_told_from_code_and_docs() {
        for name in ["LICENSE", "LICENSE-MIT", "licence.txt", "COPYING", "NOTICE"] {
            assert!(is_licence_file(name), "{name}");
        }
        for name in ["README.md", "license.rs", "LICENSES.toml", "src"] {
            assert!(!is_licence_file(name), "{name}");
        }
    }

    #[test]
    fn licence_expressions_split_into_names() {
        assert_eq!(licence_ids("MIT/Apache-2.0"), ["MIT", "Apache-2.0"]);
        assert_eq!(
            licence_ids("(MIT OR Apache-2.0) AND Unicode-3.0"),
            ["MIT", "Apache-2.0", "Unicode-3.0"]
        );
        assert_eq!(
            licence_ids("Apache-2.0 WITH LLVM-exception"),
            ["Apache-2.0"]
        );
    }

    #[test]
    fn a_licence_text_shared_by_crates_appears_once_naming_them_all() {
        let crates = [
            shipped("a", "MIT", &[("LICENSE", "same text")]),
            shipped("b", "MIT", &[("LICENSE-MIT", "same text\r\n")]),
            shipped("c", "ISC", &[("LICENSE", "other text")]),
        ];
        let out = licence_texts_render("Heading", &crates, &[]).unwrap();
        assert_eq!(out.matches("same text").count(), 1, "{out}");
        assert!(out.contains("Used by: a 1.0.0 (LICENSE), b 1.0.0 (LICENSE-MIT)"));
        assert!(out.contains("other text"));
        assert!(!out.contains("STANDARD TEXTS"));
    }

    #[test]
    fn a_crate_without_a_licence_file_gets_its_authors_and_the_standard_text() {
        let crates = [shipped("a", "MIT OR Apache-2.0", &[])];
        let standard = [
            ("MIT", "the mit text".to_owned()),
            ("Apache-2.0", "the apache text".to_owned()),
            ("BSL-1.0", "the boost text".to_owned()),
        ];
        let out = licence_texts_render("Heading", &crates, &standard).unwrap();
        assert!(out.contains("authors: An Author"));
        assert!(out.contains("the mit text") && out.contains("the apache text"));
        assert!(!out.contains("the boost text"), "only what is used");
    }

    #[test]
    fn a_crate_with_no_licence_text_anywhere_stops_the_package() {
        let crates = [shipped("a", "Unknown-1.0", &[])];
        let err = licence_texts_render("Heading", &crates, &[]).unwrap_err();
        assert!(
            err.contains("a 1.0.0") && err.contains("Unknown-1.0"),
            "{err}"
        );
    }

    #[test]
    fn licences_check_detects_drift() {
        let a = licences_render(&[dep("x", "1.0.0")]);
        assert!(a.contains("x 1.0.0"), "{a}");
        assert_ne!(a, licences_render(&[dep("x", "1.0.1")]));
    }

    #[test]
    fn licences_render_ignores_input_order() {
        let (x, y) = (dep("x", "1.0.0"), dep("y", "1.0.0"));
        assert_eq!(
            licences_render(&[x.clone(), y.clone()]),
            licences_render(&[y, x])
        );
    }

    #[test]
    fn colour_flags_literals_outside_theme() {
        let text = "let c = Color32::from_rgb(1, 2, 3);\nlet d = theme::ACCENT;\n";
        assert_eq!(
            colour_violations("crates/seacraft-gui/src/app.rs", text).len(),
            1
        );
        assert!(colour_violations("crates/seacraft-gui/src/theme.rs", text).is_empty());
    }
}
